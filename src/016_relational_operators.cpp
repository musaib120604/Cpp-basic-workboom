// Relational operators
// Comparison operators yield 1 (true) or 0 (false).

#include <iostream>
using namespace std;

int main() {
    cout << (5 < 3) << endl;
    cout << (5 > -2) << endl;
    cout << (7 <= 10) << endl;
    cout << (7 >= 10) << endl;
    cout << (5 == 8) << endl;
    cout << (5 != 8) << endl;
}
