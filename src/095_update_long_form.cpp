// Update long form
// Updating a variable by re-assigning it to itself.

#include <iostream>
using namespace std;

int main() {
    int v = 10;
    cout << v << endl;
    v = v - 2;
    cout << v << endl;
    v = v + 8;
    cout << v << endl;
    v = v * 3;
    cout << v << endl;
    v = v / 4;
    cout << v << endl;
}
