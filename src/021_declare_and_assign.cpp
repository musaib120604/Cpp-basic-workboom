// Declare and assign
// Declaring, assigning and combining variables.

#include <iostream>
using namespace std;

int main() {
    int x;       // declaration
    x = 70;      // assignment
    cout << x << endl;
    cout << "x" << endl;  // the letter x, not the variable

    int y = 3;                // declare and initialise together
    int c = 10, d = 34;       // several at once
    cout << c + d - y << endl;
}
